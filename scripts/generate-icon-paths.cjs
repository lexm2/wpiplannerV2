/**
 * Generates src/utils/iconPaths.ts from SVG files in src/assets/icons/
 *
 * Run: npm run generate-icons
 */

const fs = require('fs');
const path = require('path');

const ICONS_DIR = path.join(__dirname, '../src/assets/icons');
const OUTPUT_FILE = path.join(__dirname, '../src/utils/iconPaths.ts');

function kebabToUpperSnake(filename) {
  return filename
    .replace('.svg', '')
    .split('-')
    .map(part => part.toUpperCase())
    .join('_');
}

function kebabToCamel(filename) {
  const parts = filename.replace('.svg', '').split('-');
  return parts
    .map((part, i) => i === 0 ? part : part.charAt(0).toUpperCase() + part.slice(1))
    .join('') + 'Icon';
}

function generateIconPaths() {
  const svgFiles = fs.readdirSync(ICONS_DIR)
    .filter(file => file.endsWith('.svg'))
    .sort();

  if (svgFiles.length === 0) {
    console.error('No SVG files found in', ICONS_DIR);
    process.exit(1);
  }

  console.log(`Found ${svgFiles.length} SVG files`);

  const icons = svgFiles.map(filename => {
    const constantName = kebabToUpperSnake(filename);
    const variableName = kebabToCamel(filename);
    const svgContent = fs.readFileSync(path.join(ICONS_DIR, filename), 'utf-8')
      .trim()
      .replace(/\s+class="[^"]*"/g, '') // Remove class attributes from source SVG
      .replace(/stroke="#000000"/g, 'stroke="currentColor"') // Replace black stroke with currentColor
      .replace(/fill="#000000"/g, 'fill="currentColor"'); // Replace black fill with currentColor

    return {
      filename,
      constantName,
      variableName,
      svgContent
    };
  });

  const imports = icons
    .map(icon => `import ${icon.variableName} from '../assets/icons/${icon.filename}?url';`)
    .join('\n');

  const iconNames = icons
    .map(icon => `  | '${icon.constantName}'`)
    .join('\n');

  const iconsObject = icons
    .map(icon => `  ${icon.constantName}: ${icon.variableName},`)
    .join('\n');

  const inlineSvgsObject = icons
    .map(icon => `  ${icon.constantName}: \`${icon.svgContent}\`,`)
    .join('\n');

  const output = `/**
 * Centralized icon path constants for type-safe asset references.
 * Icons are imported from src/assets/icons/ and Vite handles base path resolution.
 *
 * Exports both URL paths (for img tags) and inline SVG content (for better CSS styling).
 *
 * AUTO-GENERATED by scripts/generate-icon-paths.js
 * Run: npm run generate-icons
 */

${imports}

export type IconName =
${iconNames};

/**
 * Icon paths for SVG assets with Vite base path resolution.
 *
 * Available icons:
${icons.map(icon => ` * - ${icon.constantName}: ${icon.filename}`).join('\n')}
 */
export const ICONS: Record<IconName, string> = {
${iconsObject}
} as const;

/**
 * Inline SVG content for icons that need CSS styling support.
 * These use currentColor and can be styled with CSS fill/stroke properties.
 */
export const INLINE_SVGS: Record<IconName, string> = {
${inlineSvgsObject}
} as const;

/**
 * Helper function to create an inline SVG with custom classes.
 * @param iconName The icon to render
 * @param className Optional CSS classes to apply
 * @returns HTML string with inline SVG
 */
export function getInlineSVG(iconName: IconName, className?: string): string {
  const svg = INLINE_SVGS[iconName];
  if (!className) return svg;

  // Add class to the SVG element
  return svg.replace('<svg', \`<svg class="\${className}"\`);
}
`;

  fs.writeFileSync(OUTPUT_FILE, output, 'utf-8');
  console.log(`✓ Generated ${OUTPUT_FILE}`);
  console.log(`  Icons: ${icons.map(i => i.constantName).join(', ')}`);
}

try {
  generateIconPaths();
} catch (error) {
  console.error('Error generating icon paths:', error);
  process.exit(1);
}
